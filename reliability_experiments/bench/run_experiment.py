def expand_model_weights_to_box_weights(weights, boxes_list):
    """
    Convert per-model weights -> per-box weight matrix
    """
    weight_matrix = []
    for m, boxes in enumerate(boxes_list):
        w = weights[m]
        weight_matrix.append([w] * len(boxes))
    return weight_matrix

